#!/usr/bin/env bash
#
# Build files that must be copied to the root of an Ubuntu Server autoinstall
# USB/ISO. This does not write to block devices.
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
OUT_DIR="${REPO_ROOT}/dist/autoinstall"
PASSWORD_HASH="${DRYCONTROLLER_AUTOINSTALL_PASSWORD_HASH:-}"
PASSWORD_HASH_FILE=""
PASSWORD_ENV_FILE=""

usage() {
  cat <<'EOF'
Usage:
  bash scripts/build-autoinstall-bundle.sh [--out DIR] [--password-hash HASH | --password-hash-file FILE | --password-env-file FILE]

Required offline apt repo for factory/site media:
  bash scripts/build-autoinstall-offline-apt-repo.sh --out DIR/drycontroller-apt

Output:
  DIR/user-data
  DIR/meta-data
  DIR/post-install.sh
  DIR/drycontroller-edge-post-install.service
  DIR/wifi.env.example
  DIR/drycontroller-edge.tar.gz
  DIR/drycontroller-apt/

Copy these files to the root of Ubuntu Server installer media and boot with:
  autoinstall ds=nocloud;s=/cdrom/

Password hash:
  Source user-data keeps a placeholder so secrets are not committed.
  Production/test media that must allow local console or password SSH login
  should pass a sha512-crypt hash generated by:
    openssl passwd -6
  Alternatively, pass a local password env file containing:
    DRYOPS_PASSWORD=your-login-password
EOF
}

read_env_value() {
  local key="$1"
  local file="$2"
  awk -v key="$key" '
    /^[[:space:]]*#/ || /^[[:space:]]*$/ { next }
    {
      line = $0
      sub(/^[[:space:]]*export[[:space:]]+/, "", line)
      name = line
      sub(/=.*/, "", name)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", name)
      if (name == key) {
        value = line
        sub(/^[^=]*=/, "", value)
        gsub(/^[[:space:]]+|[[:space:]]+$/, "", value)
        if ((substr(value, 1, 1) == "\"" && substr(value, length(value), 1) == "\"") ||
            (substr(value, 1, 1) == "\047" && substr(value, length(value), 1) == "\047")) {
          value = substr(value, 2, length(value) - 2)
        }
        print value
        found = 1
      }
    }
    END { if (!found) exit 1 }
  ' "$file"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --out)
      OUT_DIR="${2:-}"
      [ -n "$OUT_DIR" ] || { usage >&2; exit 2; }
      shift 2
      ;;
    --password-hash)
      PASSWORD_HASH="${2:-}"
      [ -n "$PASSWORD_HASH" ] || { usage >&2; exit 2; }
      shift 2
      ;;
    --password-hash-file)
      PASSWORD_HASH_FILE="${2:-}"
      [ -n "$PASSWORD_HASH_FILE" ] || { usage >&2; exit 2; }
      shift 2
      ;;
    --password-env-file)
      PASSWORD_ENV_FILE="${2:-}"
      [ -n "$PASSWORD_ENV_FILE" ] || { usage >&2; exit 2; }
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      usage >&2
      echo "unknown argument: $1" >&2
      exit 2
      ;;
  esac
done

if [ -n "$PASSWORD_HASH_FILE" ]; then
  [ -f "$PASSWORD_HASH_FILE" ] || { echo "password hash file not found: $PASSWORD_HASH_FILE" >&2; exit 2; }
  PASSWORD_HASH="$(head -n 1 "$PASSWORD_HASH_FILE" | tr -d '\r\n')"
fi

if [ -n "$PASSWORD_ENV_FILE" ]; then
  [ -f "$PASSWORD_ENV_FILE" ] || { echo "password env file not found: $PASSWORD_ENV_FILE" >&2; exit 2; }
  if [ -n "$PASSWORD_HASH" ]; then
    echo "password env file cannot be combined with --password-hash, --password-hash-file, or DRYCONTROLLER_AUTOINSTALL_PASSWORD_HASH" >&2
    exit 2
  fi
  DRYOPS_PASSWORD="$(read_env_value DRYOPS_PASSWORD "$PASSWORD_ENV_FILE" || true)"
  [ -n "$DRYOPS_PASSWORD" ] || { echo "password env file must define DRYOPS_PASSWORD" >&2; exit 2; }
  PASSWORD_HASH="$(printf '%s\n' "$DRYOPS_PASSWORD" | openssl passwd -6 -stdin)"
  unset DRYOPS_PASSWORD
fi

if [ -n "$PASSWORD_HASH" ]; then
  case "$PASSWORD_HASH" in
    '$6$REPLACE_WITH_SHA512_CRYPT_HASH'|*REPLACE_WITH_SHA512_CRYPT_HASH*)
      echo "password hash is still the placeholder" >&2
      exit 2
      ;;
    '$6$'*)
      ;;
    *)
      echo 'password hash must be a sha512-crypt value starting with $6$' >&2
      exit 2
      ;;
  esac
fi

mkdir -p "$OUT_DIR"

install -m 0644 "${REPO_ROOT}/infra/autoinstall/user-data" "${OUT_DIR}/user-data"
if [ -n "$PASSWORD_HASH" ]; then
  USER_DATA="${OUT_DIR}/user-data" PASSWORD_HASH="$PASSWORD_HASH" python3 - <<'PY'
import os
from pathlib import Path

path = Path(os.environ["USER_DATA"])
password_hash = os.environ["PASSWORD_HASH"]
text = path.read_text(encoding="utf-8")
placeholder = "$6$REPLACE_WITH_SHA512_CRYPT_HASH"
if placeholder not in text:
    raise SystemExit("password placeholder not found in user-data")
path.write_text(text.replace(placeholder, password_hash), encoding="utf-8")
PY
fi
USER_DATA_PATH="${OUT_DIR}/user-data" python3 - <<'PY'
import sys
from pathlib import Path

path = Path(__import__("os").environ["USER_DATA_PATH"])
text = path.read_text(encoding="utf-8")
effective_lines = [
    line.strip()
    for line in text.splitlines()
    if line.strip() and not line.strip().startswith("#")
]
effective = "\n".join(effective_lines)
required = [
    "http://127.0.0.1:18080",
    "python3 -m http.server 18080",
    "sources_list:",
    "disable_suites:",
]
missing = [item for item in required if item not in text]
if missing:
    print(
        "user-data must route installer apt through the ISO-local HTTP repository: "
        + ", ".join(missing),
        file=sys.stderr,
    )
    raise SystemExit(2)
for forbidden in (
    "mirrors.aliyun.com",
    "mirrors.tuna.tsinghua.edu.cn",
    "archive.ubuntu.com",
    "security.ubuntu.com",
):
    if forbidden in effective:
        print(f"user-data installer apt must not depend on external mirror: {forbidden}", file=sys.stderr)
        raise SystemExit(2)
bad = []
for lineno, line in enumerate(text.splitlines(), start=1):
    stripped = line.strip()
    if stripped.startswith("#"):
        continue
    if stripped.startswith(("uri:", "source:")) and ("file:/cdrom" in stripped or "file://cdrom" in stripped):
        bad.append(f"line {lineno}: {stripped}")
if bad:
    print(
        "user-data must not point installer apt sources directly at file:/cdrom: "
        + ", ".join(bad),
        file=sys.stderr,
    )
    raise SystemExit(2)
PY
install -m 0644 "${REPO_ROOT}/infra/autoinstall/meta-data" "${OUT_DIR}/meta-data"
install -m 0755 "${REPO_ROOT}/infra/autoinstall/post-install.sh" "${OUT_DIR}/post-install.sh"
install -m 0644 "${REPO_ROOT}/infra/autoinstall/drycontroller-edge-post-install.service" "${OUT_DIR}/drycontroller-edge-post-install.service"
install -m 0600 "${REPO_ROOT}/infra/autoinstall/wifi.env.example" "${OUT_DIR}/wifi.env.example"

# 源码 bundle 由 build-bundle-images.sh 统一产出；如果还没构建则自动触发
BUNDLE_SCRIPT="${REPO_ROOT}/tools/build-bundle-images.sh"
BUNDLE_SRC="${REPO_ROOT}/dist/drycontroller-edge.tar.gz"
if [ ! -f "$BUNDLE_SRC" ]; then
  echo "source bundle not found; running build-bundle-images.sh --bundle-only ..."
  bash "$BUNDLE_SCRIPT" --bundle-only
fi
cp "$BUNDLE_SRC" "${OUT_DIR}/drycontroller-edge.tar.gz"

cat <<EOF
Autoinstall bundle written to:
  ${OUT_DIR}

Required files:
  ${OUT_DIR}/user-data
  ${OUT_DIR}/meta-data
  ${OUT_DIR}/post-install.sh
  ${OUT_DIR}/drycontroller-edge-post-install.service
  ${OUT_DIR}/wifi.env.example
  ${OUT_DIR}/drycontroller-edge.tar.gz

Required offline apt repo:
  bash scripts/build-autoinstall-offline-apt-repo.sh --out "${OUT_DIR}/drycontroller-apt"

Before production use:
  1. Pass --password-env-file, --password-hash-file, or
     DRYCONTROLLER_AUTOINSTALL_PASSWORD_HASH so dryops can log in locally and
     over password SSH.
  2. If the install area uses WiFi, copy wifi.env.example to wifi.env and fill it.
  3. Include drycontroller-apt/ so Docker does not depend on public
     Ubuntu/Docker mirror reachability.
  4. Production identity media is intentionally unavailable until RB-5B/RB-6.
EOF

if grep -q 'REPLACE_WITH_SHA512_CRYPT_HASH' "${OUT_DIR}/user-data"; then
  cat <<EOF >&2

WARNING: ${OUT_DIR}/user-data still contains the password placeholder.
Console login and password SSH will not work until a real sha512-crypt hash is injected.
EOF
fi
